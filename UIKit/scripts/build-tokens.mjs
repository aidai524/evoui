// Generates every token artefact from tokens/nui3.tokens.json (DTCG):
//   src/nui3/css/tokens.css          @layer nui3.tokens — primitive, base, paper/night/auto, compact
//   src/nui3/theme/tokens.generated.ts  typed maps for defineTheme / checkContrast
//   tokens/dist/tokens.json          flat { "--nui-…": value } per theme
//   tokens/dist/tailwind.cjs         Tailwind preset mapped to CSS variables
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const src = JSON.parse(readFileSync(join(root, 'tokens/nui3.tokens.json'), 'utf8'))

/** Group → CSS variable prefix (02 §1). */
const PREFIX = {
  'primitive.color': 'color-',
  'primitive.font': 'font-',
  'base.font-size': 'fs-',
  'base.line-height': 'lh-',
  'base.letter-spacing': 'ls-',
  'base.space': 'space-',
  'base.radius': 'radius-',
  'base.layout': '',
  'base.density': '',
  'base.motion': '',
  'base.z': 'z-',
}

const leaves = (obj) => Object.entries(obj).filter(([k]) => !k.startsWith('$')).map(([k, v]) => [k, v.$value])

const vars = {}
for (const [path, prefix] of Object.entries(PREFIX)) {
  const [layer, group] = path.split('.')
  for (const [k, v] of leaves(src[layer][group])) vars[`--nui-${prefix}${k}`] = v
}
const themeVars = (name) => {
  const out = {}
  for (const [k, v] of leaves(src.theme[name])) out[k === 'color-scheme' ? 'color-scheme' : `--nui-${k}`] = v
  return out
}
const paper = themeVars('paper')
const night = themeVars('night')
const compact = Object.fromEntries(leaves(src.density.compact).map(([k, v]) => [`--nui-${k}`, v]))

const block = (sel, map, indent = '  ') =>
  `${indent}${sel} {\n${Object.entries(map).map(([k, v]) => `${indent}  ${k}: ${v};`).join('\n')}\n${indent}}`

const css = `/* GENERATED by scripts/build-tokens.mjs from tokens/nui3.tokens.json — do not edit. */
@layer nui3.tokens, nui3.theme, nui3.base, nui3.components, nui3.utilities;

@layer nui3.tokens {
${block(':root', vars)}

${block(':root,\n  [data-nui-theme="paper"],\n  [data-nui-theme="auto"]', paper)}

${block('[data-nui-theme="night"]', night)}

  @media (prefers-color-scheme: dark) {
${block('[data-nui-theme="auto"]', night, '    ')}
  }

${block('[data-nui-density="compact"]', compact)}

  @media (max-width: 860px) {
    :root { --nui-header-h: 72px; }
  }
}
`

const flat = { base: vars, paper, night, compact }
const tsMap = (m) => JSON.stringify(Object.fromEntries(Object.entries(m).filter(([k]) => k.startsWith('--nui-')).map(([k, v]) => [k.slice(6), v])), null, 2)

const ts = `// GENERATED by scripts/build-tokens.mjs from tokens/nui3.tokens.json — do not edit.
/** Semantic theme tokens without the --nui- prefix, e.g. { accent: '#f3b724' }. */
export type ThemeTokens = Record<string, string>

export const BASE_TOKENS: ThemeTokens = ${tsMap(vars)}

export const BUILTIN_THEMES: Record<'paper' | 'night', ThemeTokens> = {
  paper: ${tsMap(paper)},
  night: ${tsMap(night)},
}

export const COMPACT_TOKENS: ThemeTokens = ${tsMap(compact)}
`

const themeKeys = Object.keys(paper).filter((k) => k.startsWith('--nui-')).map((k) => k.slice(6))
const colorKeys = themeKeys.filter((k) => /^#|^rgba?\(/.test(src.theme.paper[k].$value))
const tailwind = `// GENERATED by scripts/build-tokens.mjs — Tailwind preset; colours resolve to CSS variables so theme switches need no rebuild.
module.exports = {
  theme: {
    extend: {
      colors: {
        nui: {
${colorKeys.map((k) => `          '${k}': 'var(--nui-${k})',`).join('\n')}
        },
      },
      fontFamily: {
        display: 'var(--nui-font-display)',
        sans: 'var(--nui-font-sans)',
        mono: 'var(--nui-font-mono)',
      },
      borderRadius: {
        none: '0px',
        DEFAULT: 'var(--nui-radius-base)',
        control: 'var(--nui-radius-control)',
        pill: 'var(--nui-radius-pill)',
      },
      maxWidth: { container: 'var(--nui-container)' },
      transitionTimingFunction: { nui: 'var(--nui-ease)' },
    },
  },
}
`

const write = (rel, text) => {
  const p = join(root, rel)
  mkdirSync(dirname(p), { recursive: true })
  writeFileSync(p, text)
}
write('src/nui3/css/tokens.css', css)
write('src/nui3/theme/tokens.generated.ts', ts)
write('tokens/dist/tokens.json', JSON.stringify(flat, null, 2) + '\n')
write('tokens/dist/tailwind.cjs', tailwind)
console.log(`tokens: ${Object.keys(vars).length} base, ${themeKeys.length} per theme, ${Object.keys(compact).length} compact`)
